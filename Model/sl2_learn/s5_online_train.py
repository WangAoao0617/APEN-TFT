# 基于滚动数据窗口更新模型，并选择验证损失最低的在线模型。
# Update models with rolling data windows and retain the online model with the lowest validation loss.


import copy
import importlib
from pathlib import Path
import warnings
import numpy as np
import pandas as pd
import torch
import torchmetrics.metric
import torchmetrics.utilities.data
from lightning.pytorch import Trainer
from pytorch_forecasting import TemporalFusionTransformer, TimeSeriesDataSet
from pytorch_forecasting.data.encoders import EncoderNormalizer, NaNLabelEncoder
from pytorch_forecasting.metrics import MAE, MAPE, RMSE, SMAPE, QuantileLoss
from sklearn.preprocessing import StandardScaler
from torch.utils.data import SubsetRandomSampler
from global_config import config

# 定义模型、数据、在线权重和日志的相对路径
# Define relative paths for models, data, online weights, and logs
MODEL_ROOT = Path(__file__).resolve().parents[1]
ARCHIVE_DIR = MODEL_ROOT.parent / "Archive"
TRANSIT_DIR = MODEL_ROOT.parent / "Transit"
TFT_NET_DIR = TRANSIT_DIR / "tft_net"
TFT_OL_DIR = TRANSIT_DIR / "tft_ol"
ONLINE_TRAIN_LOG_DIR = TRANSIT_DIR / "logs" / "online_train"


# 使用滚动窗口执行 TFT 在线学习
# Perform TFT online learning with rolling windows
class TFTOnlineLearning:

    # 完整加载由本程序生成的可信检查点
    # Fully load a trusted checkpoint generated by this program
    @staticmethod
    def _load_trusted_checkpoint(checkpoint_path):

        # 获取 NumPy 的数据类型类
        # Get NumPy data type classes
        numpy_dtype_classes = list(
            {
                value
                for value in vars(np.dtypes).values()
                if isinstance(value, type)
            }
        )

        # 动态导入 NumPy 多维数组兼容模块
        # Dynamically import the NumPy multiarray compatibility module
        numpy_multiarray = importlib.import_module("numpy.core.multiarray")

        # 设置检查点中允许加载的类型和函数
        # Set types and functions allowed in the checkpoint
        safe_globals = [
            SMAPE,
            MAE,
            MAPE,
            RMSE,
            QuantileLoss,
            EncoderNormalizer,
            NaNLabelEncoder,
            StandardScaler,
            torchmetrics.utilities.data.dim_zero_sum,
            torchmetrics.metric.jit_distributed_available,
            np.dtype,
            numpy_multiarray.scalar,
            numpy_multiarray._reconstruct,
            np.ndarray,
            *numpy_dtype_classes,
        ]

        # 仅屏蔽 Lightning 对已保存 loss 对象的重复提示
        # Suppress only Lightning's repeated notice about the saved loss object
        with warnings.catch_warnings():
            warnings.filterwarnings(
                "ignore",
                message=r"Attribute 'loss' is an instance of `nn\.Module`.*",
            )

            # 使用 PyTorch 公开接口安全加载检查点
            # Load the checkpoint with the public PyTorch interface
            with torch.serialization.safe_globals(safe_globals):
                model = TemporalFusionTransformer.load_from_checkpoint(
                    str(checkpoint_path),
                    map_location="cpu",
                )

        # 返回包含网络结构、超参数和权重的完整 TFT 模型
        # Return the complete TFT model containing architecture, hyperparameters, and weights
        return model

    # 将真实值转换为一维 NumPy 数组
    # Convert actual values to a one-dimensional NumPy array
    @staticmethod
    def _unwrap_target(target):

        # 预测结果将真实值保存为目标值和权重
        # Prediction results store actual values as target and weight
        if isinstance(target, (tuple, list)):
            target = target[0]

        # 将张量移至 CPU 并转换为 NumPy 数组
        # Move the tensor to CPU and convert it to a NumPy array
        if isinstance(target, torch.Tensor):
            target = target.detach().cpu().numpy()

        # 将真实值整理为一维数组
        # Reshape actual values into a one-dimensional array
        return np.asarray(target).reshape(-1)

    # 按离线检查点的数据参数重建时间序列数据集
    # Rebuild a time-series dataset with parameters from the offline checkpoint
    @staticmethod
    def _create_dataset(model, data, max_encoder_length, max_prediction_length):

        # 固定编码器和预测长度以保持每个目标只对应一个窗口
        # Fix encoder and prediction lengths so each target has one window
        return TimeSeriesDataSet.from_parameters(
            copy.deepcopy(model.dataset_parameters),
            data,
            stop_randomization=True,
            predict=False,
            min_encoder_length=max_encoder_length,
            max_encoder_length=max_encoder_length,
            min_prediction_length=max_prediction_length,
            max_prediction_length=max_prediction_length,
            randomize_length=None,
        )

    # 创建预测和验证使用的数据加载器
    # Create a data loader for prediction and validation
    @staticmethod
    def _create_prediction_dataloader(dataset, batch_size, num_workers):

        # 仅在 CUDA 可用时锁定内存
        # Pin memory only when CUDA is available
        return dataset.to_dataloader(
            train=False,
            batch_size=batch_size,
            num_workers=num_workers,
            pin_memory=torch.cuda.is_available(),
            persistent_workers=num_workers > 0,
        )

    # 计算模型在验证数据上的真实损失
    # Calculate the model's actual loss on validation data
    @staticmethod
    def _validation_loss(model, dataloader, trainer_kwargs):

        # 使用 Lightning 验证流程计算检查点配置的损失
        # Use Lightning validation to calculate the loss configured in the checkpoint
        validation_trainer_kwargs = copy.deepcopy(trainer_kwargs)
        validation_trainer_kwargs.pop("callbacks", None)
        validation_trainer = Trainer(
            **validation_trainer_kwargs,
            enable_checkpointing=False,
        )
        validation_results = validation_trainer.validate(
            model,
            dataloaders=dataloader,
            verbose=False,
        )
        if not validation_results or "val_loss" not in validation_results[0]:
            raise RuntimeError("The model did not return val_loss.")

        # 将模型移回 CPU 并释放验证阶段的 CUDA 缓存
        # Move the model back to CPU and release CUDA cache from validation
        validation_loss = float(validation_results[0]["val_loss"])
        model.cpu()
        model._trainer = None
        del validation_trainer
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

        # 返回单个浮点损失值
        # Return one floating-point loss value
        return validation_loss

    # 预测新数据并更新在线模型
    # Predict new data and update the online model
    @classmethod
    def online_learning(cls, df, var_group_list):

        # 打印流程名称
        # Print the process name
        print("\033[1;93m\n--- Process 7 ---  TFT Online Learning  ---\033[0m")

        # 创建空预测结果
        # Create an empty prediction result
        empty_result = pd.DataFrame(
            {
                "time_idx": pd.Series(dtype="int64"),
                "actual": pd.Series(dtype="float64"),
                "predicted": pd.Series(dtype="float64"),
            }
        )

        # 检查传入数据的类型和内容
        # Check the type and content of input data
        if not isinstance(df, pd.DataFrame):
            raise TypeError("The first argument of online_learning must be a pandas DataFrame.")
        if df.empty:
            print("\nNo data available for online learning!")
            return empty_result

        # 读取在线学习和数据加载参数
        # Read online-learning and data-loading parameters
        max_encoder_length = int(config["max_encoder_length"])
        max_prediction_length = int(config["decoder_length"])
        posterior_step = int(config["posterior_step"])
        update_step = int(config["update_step"])
        richness = int(config["richness"])
        per_ol_batches = int(config["per_ol_batches"])
        attenuation_coefficient = float(config["attenuation_coefficient"])
        emphasis_coefficient = float(config["emphasis_coefficient"])
        per_ol_epochs = int(config["per_ol_epochs"])
        batch_size = int(config["batch_size"])
        num_workers = int(config["num_workers"])
        static_train_len = max(
            update_step * per_ol_batches,
            int(config["min_static_train_len"]),
        )

        # 检查在线学习参数
        # Check online-learning parameters
        positive_parameters = {
            "max_encoder_length": max_encoder_length,
            "decoder_length": max_prediction_length,
            "posterior_step": posterior_step,
            "update_step": update_step,
            "richness": richness,
            "per_ol_batches": per_ol_batches,
            "per_ol_epochs": per_ol_epochs,
            "batch_size": batch_size,
        }
        for parameter_name, parameter_value in positive_parameters.items():
            if parameter_value <= 0:
                raise ValueError(f"{parameter_name} must be greater than zero.")
        if max_prediction_length != 1:
            raise ValueError("Online learning currently requires decoder_length to be 1.")
        if not 0 <= emphasis_coefficient <= 1:
            raise ValueError("emphasis_coefficient must be in the interval [0, 1].")
        if attenuation_coefficient < 0:
            raise ValueError("attenuation_coefficient must be non-negative.")
        if static_train_len < posterior_step + max_encoder_length:
            raise ValueError(
                "min_static_train_len must not be smaller than posterior_step plus max_encoder_length."
            )

        # 按时间顺序整理数据并重设位置索引
        # Sort data by time and reset its positional index
        required_base_columns = {"asset_id", "time_idx"}
        missing_base_columns = required_base_columns.difference(df.columns)
        if missing_base_columns:
            missing_text = ", ".join(sorted(missing_base_columns))
            raise ValueError(f"Required online-learning columns are missing: {missing_text}")
        df = df.sort_values(["asset_id", "time_idx"]).reset_index(drop=True).copy()
        df["asset_id"] = df["asset_id"].astype(str)

        # 当前滚动窗口算法只处理一条风机时间序列
        # The current rolling-window algorithm handles one turbine time series
        if df["asset_id"].nunique() != 1:
            raise ValueError("Online learning currently requires exactly one asset_id.")

        # 获取当前风场的主要监测变量
        # Get the main monitored variable for the current wind farm
        info = pd.read_csv(ARCHIVE_DIR / "feature_info.csv")
        matched_rows = info[info["wind_farm"] == config["wind_farm_id"]]
        if matched_rows.empty:
            raise ValueError("The current wind farm was not found in feature_info.csv.")
        monitoring_variable = matched_rows.iloc[0]["main_mv"]

        # 检查监测变量是否包含在变量分组结果中
        # Check whether the monitored variable is included in variable groups
        if not any(element[0] == monitoring_variable for element in var_group_list):
            raise ValueError("The main monitoring variable was not found in var_group_list.")

        # 检查离线模型权重文件
        # Check the offline model weight file
        model_0_path = TFT_NET_DIR / f"{monitoring_variable}.ckpt"
        if not model_0_path.is_file():
            print("\nWeight file not found!")
            return empty_result

        # 加载离线 TFT 模型
        # Load the offline TFT model
        current_model = cls._load_trusted_checkpoint(model_0_path)
        dataset_parameters = current_model.dataset_parameters

        # 检查离线检查点是否包含数据集参数
        # Check whether the offline checkpoint contains dataset parameters
        if dataset_parameters is None:
            raise ValueError("The offline checkpoint does not contain dataset parameters.")

        # 检查配置长度是否与离线模型一致
        # Check whether configured lengths match the offline model
        if int(dataset_parameters["max_encoder_length"]) != max_encoder_length:
            raise ValueError("max_encoder_length does not match the offline checkpoint.")
        if int(dataset_parameters["max_prediction_length"]) != max_prediction_length:
            raise ValueError("decoder_length does not match the offline checkpoint.")

        # 检查在线数据是否包含离线模型需要的全部列
        # Check whether online data contain every column required by the offline model
        required_model_columns = {
            dataset_parameters["time_idx"],
            *dataset_parameters["group_ids"],
            *dataset_parameters["static_categoricals"],
            *dataset_parameters["time_varying_known_reals"],
            *dataset_parameters["time_varying_unknown_reals"],
        }
        missing_model_columns = required_model_columns.difference(df.columns)
        if missing_model_columns:
            missing_text = ", ".join(sorted(missing_model_columns))
            raise ValueError(f"Columns required by the offline checkpoint are missing: {missing_text}")

        # 使用标准化后的均值填充模型输入中的非有限值
        # Fill non-finite model inputs with the standardized mean
        known_real_columns = list(dataset_parameters["time_varying_known_reals"])
        known_real_values = df[known_real_columns].replace(
            [np.inf, -np.inf],
            np.nan,
        )
        filled_input_count = int(known_real_values.isna().sum().sum())
        if filled_input_count > 0:
            df[known_real_columns] = known_real_values.fillna(0.0)
            print(
                f"\nFilled {filled_input_count} non-finite model input "
                "value(s) with 0"
            )

        # 不允许在线学习的目标真实值缺失
        # Do not allow missing actual targets in online learning
        target_columns = list(dataset_parameters["time_varying_unknown_reals"])
        target_values = df[target_columns].replace(
            [np.inf, -np.inf],
            np.nan,
        )
        if target_values.isna().any().any():
            raise ValueError("Online-learning target values contain NA or infinite values.")

        # 检查数据长度并计算在线更新次数
        # Check data length and calculate the number of online updates
        total_data_length = len(df)
        total_updates = (total_data_length - static_train_len) // update_step
        if total_updates <= 0:
            print("\nNo new data available for online learning!")
            return empty_result

        # 创建在线权重目录并保存初始模型权重
        # Create the online-weight directory and save initial model weights
        TFT_OL_DIR.mkdir(parents=True, exist_ok=True)
        current_model.cpu()
        torch.save(current_model.state_dict(), TFT_OL_DIR / "tft_0.pth")

        # 设置预测和验证使用的 Trainer 参数
        # Set Trainer parameters used for prediction and validation
        prediction_trainer_kwargs = {
            "devices": config["devices"],
            "accelerator": config["accelerator"],
            "precision": config["precision"],
            "logger": False,
            "enable_progress_bar": False,
            "enable_model_summary": False,
            "default_root_dir": str(ONLINE_TRAIN_LOG_DIR),
        }

        # 创建每轮预测结果列表
        # Create a list for prediction results from every update
        result_frames = []
        print("\nStarting dynamic execution ...")

        # 依次处理每个完整的新数据块
        # Process every complete new-data block in sequence
        for update_idx in range(total_updates):
            print(f"\nStarting update {update_idx + 1}/{total_updates} ...")

            # 计算监测、验证和训练区间
            # Calculate monitoring, validation, and training ranges
            new_data_start = static_train_len + update_idx * update_step
            validation_start = new_data_start - posterior_step - max_encoder_length
            monitoring_start = new_data_start - max_encoder_length
            validation_end = static_train_len + (update_idx + 1) * update_step

            # 创建监测数据集并预测当前新数据
            # Create the monitoring dataset and predict current new data
            monitoring_df = df.iloc[monitoring_start:validation_end].copy()
            monitoring_dataset = cls._create_dataset(
                current_model,
                monitoring_df,
                max_encoder_length,
                max_prediction_length,
            )
            monitoring_dataloader = cls._create_prediction_dataloader(
                monitoring_dataset,
                batch_size,
                num_workers,
            )
            prediction = current_model.predict(
                monitoring_dataloader,
                mode="prediction",
                return_y=True,
                return_index=True,
                trainer_kwargs=copy.deepcopy(prediction_trainer_kwargs),
            )

            # 整理本轮预测值、真实值和时间索引
            # Arrange predicted values, actual values, and time indices for this update
            temp_df = pd.DataFrame(
                {
                    "time_idx": prediction.index["time_idx"].to_numpy(),
                    "actual": cls._unwrap_target(prediction.y),
                    "predicted": prediction.output.detach().cpu().numpy().reshape(-1),
                }
            )
            new_time_indices = set(
                df.iloc[new_data_start:validation_end]["time_idx"].tolist()
            )
            temp_df = temp_df[temp_df["time_idx"].isin(new_time_indices)]
            temp_df = temp_df.drop_duplicates(subset=["time_idx"], keep="last")
            result_frames.append(temp_df.reset_index(drop=True))

            # 将模型移回 CPU 并释放预测阶段的 CUDA 缓存
            # Move the model back to CPU and release CUDA cache from prediction
            del prediction
            current_model.cpu()
            current_model._trainer = None
            if torch.cuda.is_available():
                torch.cuda.empty_cache()

            # 创建验证数据集和数据加载器
            # Create the validation dataset and data loader
            validation_df = df.iloc[validation_start:validation_end].copy()
            validation_dataset = cls._create_dataset(
                current_model,
                validation_df,
                max_encoder_length,
                max_prediction_length,
            )
            validation_dataloader = cls._create_prediction_dataloader(
                validation_dataset,
                batch_size,
                num_workers,
            )

            # 从目前可用的数据创建训练序列池
            # Create the training-sequence pool from currently available data
            training_pool_df = df.iloc[:validation_end].copy()
            training_dataset = cls._create_dataset(
                current_model,
                training_pool_df,
                max_encoder_length,
                max_prediction_length,
            )
            if len(training_dataset) <= update_step:
                raise ValueError("The online training-sequence pool is too small.")

            # 按预测时间划分近期和历史序列
            # Divide recent and historical sequences by prediction time
            prediction_times = training_dataset.decoded_index[
                "time_idx_first_prediction"
            ].to_numpy()
            ordered_indices = np.argsort(prediction_times)
            recent_indices = ordered_indices[-update_step:]
            historical_indices = ordered_indices[:-update_step]

            # 计算近期和历史采样数量
            # Calculate recent and historical sample counts
            num_samples = update_step * per_ol_batches
            requested_high_samples = int(num_samples * emphasis_coefficient)
            requested_low_samples = num_samples - requested_high_samples
            num_low_samples = min(requested_low_samples, len(historical_indices))
            num_high_samples = num_samples - num_low_samples

            # 计算越靠近当前时刻越大的历史采样权重
            # Calculate larger historical sampling weights closer to the current time
            if num_low_samples > 0:
                historical_weights = np.linspace(
                    0.1,
                    1.0,
                    len(historical_indices),
                )
                historical_weights = historical_weights**attenuation_coefficient
                historical_weights /= historical_weights.sum()
            else:
                historical_weights = None

            # 保存当前模型和所有独立候选模型
            # Store the current model and all independent candidate models
            models_to_evaluate = [("current_model", current_model)]

            # 独立训练每个候选模型
            # Train every candidate model independently
            for candidate_idx in range(richness):
                random_seed = update_idx * richness + candidate_idx
                random_generator = np.random.default_rng(random_seed)

                # 分别抽取近期和历史训练序列
                # Sample recent and historical training sequences separately
                sampled_high = random_generator.choice(
                    recent_indices,
                    size=num_high_samples,
                    replace=True,
                )
                if num_low_samples > 0:
                    sampled_low = random_generator.choice(
                        historical_indices,
                        size=num_low_samples,
                        replace=False,
                        p=historical_weights,
                    )
                    sampled_indices = np.concatenate([sampled_high, sampled_low])
                else:
                    sampled_indices = sampled_high

                # 创建本候选模型专用的采样器和数据加载器
                # Create a sampler and data loader dedicated to this candidate
                torch_generator = torch.Generator().manual_seed(random_seed)
                sampler = SubsetRandomSampler(
                    sampled_indices.tolist(),
                    generator=torch_generator,
                )
                train_dataloader = training_dataset.to_dataloader(
                    train=True,
                    batch_size=batch_size,
                    sampler=sampler,
                    shuffle=False,
                    drop_last=False,
                    num_workers=num_workers,
                    pin_memory=torch.cuda.is_available(),
                    persistent_workers=num_workers > 0,
                )

                # 从当前最佳模型复制一个独立候选模型
                # Copy an independent candidate from the current best model
                current_model.cpu()
                candidate_model = copy.deepcopy(current_model)
                trainer = Trainer(
                    max_epochs=per_ol_epochs,
                    devices=config["devices"],
                    accelerator=config["accelerator"],
                    precision=config["precision"],
                    num_sanity_val_steps=0,
                    logger=False,
                    enable_progress_bar=False,
                    enable_model_summary=False,
                    enable_checkpointing=False,
                    default_root_dir=str(ONLINE_TRAIN_LOG_DIR),
                )

                # 外部验证将在全部候选模型训练完成后统一执行
                # External validation runs after all candidate models are trained
                with warnings.catch_warnings():
                    warnings.filterwarnings(
                        "ignore",
                        message=r"You defined a `validation_step` but have no `val_dataloader`.*",
                    )
                    warnings.filterwarnings(
                        "ignore",
                        message=r"ReduceLROnPlateau conditioned on metric val_loss.*",
                    )
                    trainer.fit(
                        candidate_model,
                        train_dataloaders=train_dataloader,
                    )
                candidate_model.cpu()
                candidate_model._trainer = None
                del trainer
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                models_to_evaluate.append(
                    (f"candidate_{candidate_idx + 1}", candidate_model)
                )

            # 在同一验证数据上选择损失最低的模型
            # Select the model with the lowest loss on the same validation data
            best_model = None
            best_loss = float("inf")
            best_name = ""
            for model_name, evaluated_model in models_to_evaluate:
                validation_loss = cls._validation_loss(
                    evaluated_model,
                    validation_dataloader,
                    prediction_trainer_kwargs,
                )
                if np.isfinite(validation_loss) and validation_loss < best_loss:
                    best_model = evaluated_model
                    best_loss = validation_loss
                    best_name = model_name

            # 检查本轮是否得到有效模型
            # Check whether this update produced a valid model
            if best_model is None:
                raise RuntimeError("No model produced a finite validation loss.")

            # 保存本轮选择的在线模型权重
            # Save the online-model weights selected in this update
            current_model = best_model.cpu()
            model_name = TFT_OL_DIR / f"tft_{update_idx + 1}.pth"
            torch.save(current_model.state_dict(), model_name)
            print(
                f"Best model: {best_name}; "
                f"Validation loss: {best_loss:.6f}"
            )

        # 合并并返回全部在线预测结果
        # Combine and return all online prediction results
        if result_frames:
            df_result = pd.concat(result_frames, ignore_index=True)
        else:
            df_result = empty_result
        print("\nOnline learning is finished ...")
        print(f"Online model weights saved to {TFT_OL_DIR}")
        return df_result
