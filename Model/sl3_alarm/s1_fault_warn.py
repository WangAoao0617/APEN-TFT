# 使用已训练的 TFT 检查点预测新数据，并根据 EWMA 绝对偏差进行故障预警。
# Use trained TFT checkpoints to predict new data and issue EWMA-based fault warnings.

import importlib
from pathlib import Path
import warnings
import numpy as np
import pandas as pd
import torch
import torchmetrics.metric
import torchmetrics.utilities.data
from pytorch_forecasting import TemporalFusionTransformer
from pytorch_forecasting.data.encoders import EncoderNormalizer, NaNLabelEncoder
from pytorch_forecasting.metrics import MAE, MAPE, RMSE, SMAPE, QuantileLoss
from sklearn.preprocessing import StandardScaler

# 导入统一加载的全局参数
# Import centrally loaded global parameters
from global_config import config

# 获取模型和中转目录
# Get the model and transit directories
MODEL_ROOT = Path(__file__).resolve().parents[1]
TRANSIT_DIR = MODEL_ROOT.parent / "Transit"
TFT_NET_DIR = TRANSIT_DIR / "tft_net"
ALARM_LOG_DIR = TRANSIT_DIR / "logs" / "alarm"
ALARM_RESULT_PATH = TRANSIT_DIR / "tft_alarm_results.xlsx"


# 加载 TFT 预测头并导出分位数预警结果
# Load TFT prediction heads and export quantile warning results
class TFTFaultWarning:

    # 将真实值转换为一维 NumPy 数组
    # Convert actual values to a one-dimensional NumPy array
    @staticmethod
    def _unwrap_target(target):
        # QuantilePrediction 将真实值保存为（目标值，权重）
        # QuantilePrediction stores actual values as (target, weight)
        if isinstance(target, (tuple, list)):
            target = target[0]

        # 将张量从计算设备移至 CPU 并转换为 NumPy 数组
        # Move the tensor from its computing device to CPU and convert it to a NumPy array
        if isinstance(target, torch.Tensor):
            target = target.detach().cpu().numpy()

        # 将真实值整理为一维数组
        # Reshape the actual values into a one-dimensional array
        return np.asarray(target).reshape(-1)

    # 生成符合 Excel 限制且不重复的工作表名称
    # Generate a unique worksheet name within Excel limits
    @staticmethod
    def _sheet_name(name, used_names):
        # Excel 工作表名称最多包含 31 个字符
        # An Excel worksheet name can contain at most 31 characters
        base = str(name)[:31] or "result"
        candidate = base
        suffix = 1

        # 为重复名称添加数字后缀
        # Add a numeric suffix to duplicated names
        while candidate in used_names:
            tail = f"_{suffix}"
            candidate = f"{base[:31 - len(tail)]}{tail}"
            suffix += 1

        # 记录并返回当前工作表名称
        # Record and return the current worksheet name
        used_names.add(candidate)
        return candidate

    # 完整加载由本程序生成的可信检查点
    # Fully load a trusted checkpoint generated by this program
    @staticmethod
    def _load_trusted_checkpoint(checkpoint_path):
        # 获取 NumPy 的数据类型类
        # Get NumPy data type classes
        numpy_dtype_classes = list({value for value in vars(np.dtypes).values() if isinstance(value, type)})

        # 动态导入 NumPy 多维数组兼容模块
        # Dynamically import the NumPy multiarray compatibility module
        numpy_multiarray = importlib.import_module("numpy.core.multiarray")

        # 设置检查点中允许加载的类型和函数
        # Set types and functions allowed in the checkpoint
        safe_globals = [
            SMAPE,
            MAE,
            MAPE,
            RMSE,
            QuantileLoss,
            EncoderNormalizer,
            NaNLabelEncoder,
            StandardScaler,
            torchmetrics.utilities.data.dim_zero_sum,
            torchmetrics.metric.jit_distributed_available,
            np.dtype,
            numpy_multiarray.scalar,
            numpy_multiarray._reconstruct,
            np.ndarray,
            *numpy_dtype_classes,
        ]

        # 仅屏蔽 Lightning 对已保存 loss 对象的重复提示
        # Suppress only Lightning's repeated notice about the saved loss object
        with warnings.catch_warnings():
            warnings.filterwarnings(
                "ignore",
                message=r"Attribute 'loss' is an instance of `nn\.Module`.*",
            )

            # 使用 PyTorch 公开接口安全加载检查点
            # Load the checkpoint with the public PyTorch interface
            with torch.serialization.safe_globals(safe_globals):
                model = TemporalFusionTransformer.load_from_checkpoint(
                    str(checkpoint_path),
                    map_location="cpu",
                )

        # 返回包含网络结构、超参数和权重的完整 TFT 模型
        # Return the complete TFT model containing architecture, hyperparameters, and weights
        return model

    # 预测新数据并将 EWMA 预警结果写入 Excel
    # Predict new data and write EWMA warning results to Excel
    @classmethod
    def predict_and_warn(
        cls,
        datasets,
        new_data=None,
        output_path=None,
    ):
        # 打印流程名称和当前任务提示
        # Print the process name and current-task message
        print("\033[1;93m\n" "--- Process 8 ---  TFT Prediction & Fault Warning  ---" "\033[0m")

        # 设置 TFT 检查点目录
        # Set the TFT checkpoint directory
        checkpoint_dir = TFT_NET_DIR

        # 检查全部监测变量的权重文件是否存在
        # Check whether all weight files for monitored variables exist
        checkpoint_paths = {
            monitoring_variable: checkpoint_dir / f"{monitoring_variable}.ckpt" for monitoring_variable in datasets
        }
        if not checkpoint_paths or not all(checkpoint_path.is_file() for checkpoint_path in checkpoint_paths.values()):
            print("\nWeight file not found!\n")
            return {}

        # 打印当前任务提示
        # Print the current-task message
        print("\nSimulating fault warning ...")

        # 设置默认结果文件路径
        # Set the default result-file path
        if output_path is None:
            output_path = ALARM_RESULT_PATH
        else:
            output_path = TRANSIT_DIR / Path(output_path).name

        # 将输出路径转换为绝对路径并确保父目录存在
        # Convert the output path to an absolute path and ensure its parent directory exists
        output_path = Path(output_path).resolve()
        output_path.parent.mkdir(parents=True, exist_ok=True)

        # 读取 EWMA 系数和报警阈值标准差倍数
        # Read the EWMA factor and alarm-threshold standard-deviation ratio
        alpha = float(config.get("alarm_ewma_alpha", 0.2))
        std_ratio = float(config.get("alarm_threshold_std_ratio", 3.0))

        # 检查 EWMA 系数是否位于有效区间
        # Check whether the EWMA factor is within its valid interval
        if not 0 < alpha <= 1:
            raise ValueError("alarm_ewma_alpha must be in the interval (0, 1].")

        # 检查阈值标准差倍数是否为非负数
        # Check whether the threshold standard-deviation ratio is non-negative
        if std_ratio < 0:
            raise ValueError("alarm_threshold_std_ratio must be non-negative.")

        # 读取分位数、批大小和数据加载进程数
        # Read quantiles, batch size, and the number of data-loading workers
        configured_quantiles = config.get("quan_forecast", {}).get("quantile", [])
        batch_size = int(config["batch_size"])
        num_workers = int(config["num_workers"])

        # 创建结果字典和工作表名称集合
        # Create the result dictionary and worksheet-name set
        result_dfs = {}
        used_sheet_names = set()

        # 创建 Excel 工作簿并将各监测变量的结果写入独立工作表
        # Create the Excel workbook and write each monitored variable to a separate worksheet
        with pd.ExcelWriter(output_path, engine="openpyxl") as writer:

            # 先创建临时工作表，避免预测提前失败时由空工作簿掩盖原始异常
            # Create a temporary sheet so an empty workbook does not mask an earlier prediction error
            placeholder_sheet = "_generation_status"
            pd.DataFrame({"status": ["Prediction is still being generated."]}).to_excel(
                writer,
                sheet_name=placeholder_sheet,
                index=False,
            )

            # 依次处理每一个监测变量及其时间序列数据集
            # Process every monitored variable and its time-series dataset in sequence
            for monitoring_variable, dataset_pair in datasets.items():

                # 获取已检查的当前监测变量权重文件路径
                # Get the checked weight-file path for the current monitored variable
                checkpoint_path = checkpoint_paths[monitoring_variable]

                # 将验证数据集转换为预测数据加载器
                # Convert the validation dataset to a prediction data loader
                validation = dataset_pair["validation"]
                dataloader = validation.to_dataloader(
                    train=False,
                    batch_size=batch_size,
                    num_workers=num_workers,
                    pin_memory=torch.cuda.is_available(),
                    persistent_workers=num_workers > 0,
                )

                # 加载本程序训练并保存的可信 TFT 检查点
                # Load the trusted TFT checkpoint trained and saved by this program
                model = cls._load_trusted_checkpoint(checkpoint_path)

                # 执行分位数预测，并关闭无实际用途的默认日志和进度输出
                # Run quantile prediction and disable unnecessary default logging and progress output
                prediction = model.predict(
                    dataloader,
                    mode="quantiles",
                    return_y=True,
                    return_index=True,
                    trainer_kwargs={
                        "logger": False,
                        "enable_progress_bar": False,
                        "enable_model_summary": False,
                        "default_root_dir": str(ALARM_LOG_DIR),
                    },
                )

                # 提取预测张量并转换为 NumPy 数组
                # Extract the prediction tensor and convert it to a NumPy array
                predicted = prediction.output
                if isinstance(predicted, torch.Tensor):
                    predicted = predicted.detach().cpu().numpy()
                predicted = np.asarray(predicted)

                # 当前解码长度为 1，因此仅保留第一个预测步
                # The current decoder length is 1, so retain only the first prediction horizon
                if predicted.ndim == 3:
                    predicted = predicted[:, 0, :]
                elif predicted.ndim == 1:
                    predicted = predicted[:, None]

                # 提取真实值和每条预测对应的时间索引
                # Extract actual values and the time index corresponding to each prediction
                actual = cls._unwrap_target(prediction.y)
                prediction_index = prediction.index.reset_index(drop=True)

                # 对齐预测值、真实值和索引的行数
                # Align the row counts of predictions, actual values, and indices
                row_count = min(
                    len(predicted),
                    len(actual),
                    len(prediction_index),
                )
                predicted = predicted[:row_count]
                actual = actual[:row_count]
                prediction_index = prediction_index.iloc[:row_count].copy()

                # 传入新数据时，只保留其 time_idx 对应的预测结果
                # When new data is provided, retain only predictions matching its time_idx values
                if new_data is not None and "time_idx" in new_data.columns and "time_idx" in prediction_index.columns:
                    new_time_idx = set(new_data["time_idx"].tolist())
                    keep = prediction_index["time_idx"].isin(new_time_idx).to_numpy()
                    predicted = predicted[keep]
                    actual = actual[keep]
                    prediction_index = prediction_index.loc[keep].reset_index(drop=True)

                # 未匹配到新数据时主动终止，避免生成无效结果文件
                # Stop explicitly when no new data is matched to avoid an invalid result file
                if len(predicted) == 0:
                    raise ValueError(
                        f"No new predictions remain for '{monitoring_variable}'. "
                        "Check the time_idx values in new_data."
                    )

                # 优先读取检查点中的分位数，数量不一致时使用输出列索引
                # Prefer checkpoint quantiles and use output-column indices if their counts differ
                model_quantiles = getattr(model.loss, "quantiles", None)
                quantiles = list(model_quantiles or configured_quantiles)
                if len(quantiles) != predicted.shape[1]:
                    quantiles = list(range(predicted.shape[1]))

                # 创建当前监测变量对应的结果数据框
                # Create the result DataFrame for the current monitored variable
                result_df = pd.DataFrame(index=prediction_index.index)
                result_df.index.name = "row"

                # 为每个分位数依次生成五列预测与预警信息
                # Generate five adjacent prediction and warning columns for each quantile
                for column_index, quantile in enumerate(quantiles):

                    # 生成分位数列名前缀并提取当前分位数预测值
                    # Generate the quantile column prefix and extract its predictions
                    if isinstance(quantile, (float, np.floating)):
                        label = f"q{quantile:g}"
                    else:
                        label = f"q{quantile}"
                    predicted_values = predicted[:, column_index]

                    # 计算预测值与真实值绝对偏差的 EWMA 序列
                    # Calculate the EWMA series of absolute prediction errors
                    ewma_deviation = pd.Series(np.abs(predicted_values - actual)).ewm(alpha=alpha, adjust=False).mean()

                    # 根据 EWMA 均值及标准差计算当前分位数的报警阈值
                    # Calculate the current quantile's alarm threshold from the EWMA mean and deviation
                    threshold = float(ewma_deviation.mean() + std_ratio * ewma_deviation.std(ddof=0))

                    # 按预测值、真实值、EWMA 偏差、阈值和报警标志的顺序写入列组
                    # Write each group as prediction, actual, EWMA deviation, threshold, and alarm flag
                    result_df[f"{label}_predicted"] = predicted_values
                    result_df[f"{label}_actual"] = actual
                    result_df[f"{label}_ewma_abs_deviation"] = ewma_deviation.to_numpy()
                    result_df[f"{label}_threshold"] = threshold
                    result_df[f"{label}_alarm"] = (ewma_deviation > threshold).astype("int8")

                # 保存当前数据框，并为当前监测变量生成工作表名称
                # Store the current DataFrame and generate its worksheet name
                result_dfs[monitoring_variable] = result_df
                sheet_name = cls._sheet_name(
                    monitoring_variable,
                    used_sheet_names,
                )

                # 将当前监测变量的数据框写入独立工作表
                # Write the current monitored-variable DataFrame to a separate worksheet
                result_df.to_excel(
                    writer,
                    sheet_name=sheet_name,
                    index=False,
                )

                # 打印当前监测变量的预测结果保存信息
                # Print information about the saved prediction results
                print(
                    f"    - {monitoring_variable}: " f"{len(result_df)} predictions saved to sheet " f"'{sheet_name}'"
                )

            # 所有结果写入成功后删除临时工作表
            # Remove the temporary worksheet after all results are written successfully
            writer.book.remove(writer.book[placeholder_sheet])

        # 打印结果文件保存完成提示
        # Print the result-file completion message
        print("\nFault-warning results have been saved!\n")

        # 返回以监测变量名称为键的数据框字典
        # Return the DataFrame dictionary keyed by monitored-variable names
        return result_dfs
